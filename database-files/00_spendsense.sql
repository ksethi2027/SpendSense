DROP DATABASE IF EXISTS spendsense;
CREATE DATABASE spendsense
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;
USE spendsense;

-- ====================  TABLES  ==============================

CREATE TABLE User (
    user_id     INT            NOT NULL AUTO_INCREMENT,
    first_name  VARCHAR(60)    NOT NULL,
    last_name   VARCHAR(60)    NOT NULL,
    email       VARCHAR(120)   NOT NULL UNIQUE,
    password    VARCHAR(255)   NOT NULL,
    university  VARCHAR(120),
    role_type   ENUM('student','employee','analyst','admin') NOT NULL DEFAULT 'student',
    PRIMARY KEY (user_id)
);

CREATE TABLE Admin_Log (
    log_id       INT         NOT NULL AUTO_INCREMENT,
    user_id      INT         NOT NULL,
    action_type  VARCHAR(60) NOT NULL,
    target_table VARCHAR(60),
    target_id    INT,
    description  TEXT,
    timestamp    DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (log_id),
    CONSTRAINT fk_al_user FOREIGN KEY (user_id) REFERENCES User(user_id)
      ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Semester (
    sem_id      INT           NOT NULL AUTO_INCREMENT,
    user_id     INT           NOT NULL,
    semName     VARCHAR(60)   NOT NULL,
    startDate   DATE          NOT NULL,
    endDate     DATE          NOT NULL,
    totalBudget DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    PRIMARY KEY (sem_id),
    CONSTRAINT fk_sem_user FOREIGN KEY (user_id) REFERENCES User(user_id)
      ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Tuition_Payment (
    payment_id INT           NOT NULL AUTO_INCREMENT,
    sem_id     INT           NOT NULL,
    amountDue  DECIMAL(10,2) NOT NULL,
    amountPaid DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    dueDate    DATE          NOT NULL,
    paidDate   DATE,
    status     ENUM('pending','partial','paid','overdue') NOT NULL DEFAULT 'pending',
    PRIMARY KEY (payment_id),
    CONSTRAINT fk_tp_sem FOREIGN KEY (sem_id) REFERENCES Semester(sem_id)
      ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Expense_Category (
    category_id  INT         NOT NULL AUTO_INCREMENT,
    categoryName VARCHAR(80) NOT NULL UNIQUE,
    description  TEXT,
    PRIMARY KEY (category_id)
);

CREATE TABLE Expense (
    expense_id  INT           NOT NULL AUTO_INCREMENT,
    user_id     INT           NOT NULL,
    category_id INT           NOT NULL,
    amount      DECIMAL(10,2) NOT NULL,
    description VARCHAR(255),
    expenseDate DATE          NOT NULL,
    is_academic TINYINT(1)    NOT NULL DEFAULT 0,
    is_shared   TINYINT(1)    NOT NULL DEFAULT 0,
    PRIMARY KEY (expense_id),
    CONSTRAINT fk_exp_user FOREIGN KEY (user_id) REFERENCES User(user_id)
      ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_exp_cat  FOREIGN KEY (category_id) REFERENCES Expense_Category(category_id)
      ON UPDATE CASCADE
);

CREATE TABLE Student_Discount (
    discount_id  INT          NOT NULL AUTO_INCREMENT,
    discountName VARCHAR(80)  NOT NULL,
    discountCode VARCHAR(30),
    discountpct  DECIMAL(5,2) NOT NULL,
    validFrom    DATE         NOT NULL,
    validUntil   DATE,
    PRIMARY KEY (discount_id)
);

CREATE TABLE Expense_Discount (
    expense_id  INT NOT NULL,
    discount_id INT NOT NULL,
    PRIMARY KEY (expense_id, discount_id),
    CONSTRAINT fk_ed_exp  FOREIGN KEY (expense_id)  REFERENCES Expense(expense_id)
      ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_ed_disc FOREIGN KEY (discount_id) REFERENCES Student_Discount(discount_id)
      ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Friend (
    friend_id  INT          NOT NULL AUTO_INCREMENT,
    user_id    INT          NOT NULL,
    friendName VARCHAR(120) NOT NULL,
    email      VARCHAR(120),
    PRIMARY KEY (friend_id),
    CONSTRAINT fk_fr_user FOREIGN KEY (user_id) REFERENCES User(user_id)
      ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Split_Expense (
    split_id    INT           NOT NULL AUTO_INCREMENT,
    expense_id  INT           NOT NULL,
    friend_id   INT           NOT NULL,
    shareAmount DECIMAL(10,2) NOT NULL,
    status      ENUM('pending','settled') NOT NULL DEFAULT 'pending',
    settledDate DATE,
    PRIMARY KEY (split_id),
    CONSTRAINT fk_se_exp FOREIGN KEY (expense_id) REFERENCES Expense(expense_id)
      ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_se_fr  FOREIGN KEY (friend_id)  REFERENCES Friend(friend_id)
      ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Savings_Goal (
    goal_id      INT           NOT NULL AUTO_INCREMENT,
    user_id      INT           NOT NULL,
    goalName     VARCHAR(80)   NOT NULL,
    targetAmount DECIMAL(10,2) NOT NULL,
    savedAmount  DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    targetDate   DATE,
    PRIMARY KEY (goal_id),
    CONSTRAINT fk_sg_user FOREIGN KEY (user_id) REFERENCES User(user_id)
      ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Textbook (
    textbook_id INT          NOT NULL AUTO_INCREMENT,
    user_id     INT          NOT NULL,
    title       VARCHAR(200) NOT NULL,
    isbn        VARCHAR(20),
    courseName  VARCHAR(100),
    PRIMARY KEY (textbook_id),
    CONSTRAINT fk_tb_user FOREIGN KEY (user_id) REFERENCES User(user_id)
      ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Textbook_Price (
    price_id    INT          NOT NULL AUTO_INCREMENT,
    textbook_id INT          NOT NULL,
    vendor      VARCHAR(80)  NOT NULL,
    price       DECIMAL(8,2) NOT NULL,
    `condition` ENUM('new','used','digital','rental') NOT NULL DEFAULT 'new',
    PRIMARY KEY (price_id),
    CONSTRAINT fk_tbp_tb FOREIGN KEY (textbook_id) REFERENCES Textbook(textbook_id)
      ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Peer_Transaction (
    transaction_id INT           NOT NULL AUTO_INCREMENT,
    user_id        INT           NOT NULL,
    platform       VARCHAR(60)   NOT NULL,
    counterparty_name VARCHAR(120) NOT NULL,
    amount         DECIMAL(10,2) NOT NULL,
    direction      ENUM('sent','received') NOT NULL,
    date_t         DATE          NOT NULL,
    PRIMARY KEY (transaction_id),
    CONSTRAINT fk_ptr_user FOREIGN KEY (user_id) REFERENCES User(user_id)
      ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Income (
    income_id       INT           NOT NULL AUTO_INCREMENT,
    user_id         INT           NOT NULL,
    source_id       INT,
    category_income VARCHAR(60)   NOT NULL,
    amount_income   DECIMAL(10,2) NOT NULL,
    date_income     DATE          NOT NULL,
    PRIMARY KEY (income_id),
    CONSTRAINT fk_inc_user FOREIGN KEY (user_id) REFERENCES User(user_id)
      ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Insurance (
    insurance_id    INT          NOT NULL AUTO_INCREMENT,
    user_id         INT          NOT NULL,
    category_i      VARCHAR(60)  NOT NULL,
    provider        VARCHAR(80)  NOT NULL,
    monthly_premium DECIMAL(8,2) NOT NULL,
    due_date        INT          NOT NULL,
    PRIMARY KEY (insurance_id),
    CONSTRAINT fk_ins_user FOREIGN KEY (user_id) REFERENCES User(user_id)
      ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Housing_Bill (
    bill_id     INT           NOT NULL AUTO_INCREMENT,
    user_id     INT           NOT NULL,
    category_hb VARCHAR(60)   NOT NULL,
    amount_hb   DECIMAL(10,2) NOT NULL,
    due_date_hb DATE          NOT NULL,
    paid_date   DATE,
    PRIMARY KEY (bill_id),
    CONSTRAINT fk_hb_user FOREIGN KEY (user_id) REFERENCES User(user_id)
      ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Financial_Analyst (
    analyst_id INT          NOT NULL AUTO_INCREMENT,
    user_id    INT          NOT NULL UNIQUE,
    name       VARCHAR(120) NOT NULL,
    email      VARCHAR(120) NOT NULL UNIQUE,
    PRIMARY KEY (analyst_id),
    CONSTRAINT fk_fa_user FOREIGN KEY (user_id) REFERENCES User(user_id)
      ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Portfolio (
    portfolio_id   INT           NOT NULL AUTO_INCREMENT,
    user_id        INT           NOT NULL,
    portfolio_name VARCHAR(100)  NOT NULL,
    total_value    DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    created_at     DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (portfolio_id),
    CONSTRAINT fk_pf_user FOREIGN KEY (user_id) REFERENCES User(user_id)
      ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Holding (
    holding_id     INT            NOT NULL AUTO_INCREMENT,
    portfolio_id   INT            NOT NULL,
    asset_name     VARCHAR(100)   NOT NULL,
    asset_type     ENUM('stock','bond','ETF','crypto','cash','other') NOT NULL DEFAULT 'stock',
    quantity       DECIMAL(14,6)  NOT NULL DEFAULT 0,
    current_value  DECIMAL(14,2)  NOT NULL DEFAULT 0.00,
    allocation_pct DECIMAL(5,2)   NOT NULL DEFAULT 0.00,
    PRIMARY KEY (holding_id),
    CONSTRAINT fk_hd_pf FOREIGN KEY (portfolio_id) REFERENCES Portfolio(portfolio_id)
      ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Portfolio_Transaction (
    transaction_id   INT           NOT NULL AUTO_INCREMENT,
    portfolio_id     INT           NOT NULL,
    transaction_date DATE          NOT NULL,
    transaction_type ENUM('buy','sell','dividend','deposit','withdrawal') NOT NULL,
    amount           DECIMAL(14,2) NOT NULL,
    PRIMARY KEY (transaction_id),
    CONSTRAINT fk_pt_pf FOREIGN KEY (portfolio_id) REFERENCES Portfolio(portfolio_id)
      ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE Time_Period (
    period_id   INT  NOT NULL AUTO_INCREMENT,
    start_date  DATE NOT NULL,
    end_date    DATE NOT NULL,
    granularity ENUM('daily','weekly','monthly','quarterly','yearly') NOT NULL DEFAULT 'monthly',
    PRIMARY KEY (period_id)
);

CREATE TABLE Spending_Summary (
    summary_id      INT           NOT NULL AUTO_INCREMENT,
    user_id         INT           NOT NULL,
    analyst_id      INT,
    period_id       INT           NOT NULL,
    total_spent     DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    avg_spending    DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    trend_direction ENUM('up','down','flat') NOT NULL DEFAULT 'flat',
    PRIMARY KEY (summary_id),
    CONSTRAINT fk_ss_user   FOREIGN KEY (user_id)    REFERENCES User(user_id)
      ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_ss_ana    FOREIGN KEY (analyst_id)  REFERENCES Financial_Analyst(analyst_id)
      ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT fk_ss_period FOREIGN KEY (period_id)   REFERENCES Time_Period(period_id)
      ON UPDATE CASCADE
);

CREATE TABLE Performance_Report (
    report_id    INT         NOT NULL AUTO_INCREMENT,
    analyst_id   INT         NOT NULL,
    portfolio_id INT         NOT NULL,
    period_id    INT         NOT NULL,
    report_type  VARCHAR(60) NOT NULL,
    summary_text TEXT,
    generated_at DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (report_id),
    CONSTRAINT fk_pr_ana FOREIGN KEY (analyst_id)   REFERENCES Financial_Analyst(analyst_id)
      ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_pr_pf  FOREIGN KEY (portfolio_id) REFERENCES Portfolio(portfolio_id)
      ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_pr_tp  FOREIGN KEY (period_id)    REFERENCES Time_Period(period_id)
      ON UPDATE CASCADE
);

CREATE TABLE Risk_Return_Profile (
    profile_id   INT          NOT NULL AUTO_INCREMENT,
    portfolio_id INT          NOT NULL,
    period_id    INT          NOT NULL,
    risk_level   ENUM('low','medium','high') NOT NULL DEFAULT 'medium',
    return_rate  DECIMAL(6,4) NOT NULL DEFAULT 0.0000,
    volatility   DECIMAL(6,4) NOT NULL DEFAULT 0.0000,
    PRIMARY KEY (profile_id),
    CONSTRAINT fk_rr_pf FOREIGN KEY (portfolio_id) REFERENCES Portfolio(portfolio_id)
      ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_rr_tp FOREIGN KEY (period_id)    REFERENCES Time_Period(period_id)
      ON UPDATE CASCADE
);


